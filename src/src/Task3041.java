public class Task3041 {
    public int maxSelectedElements(int[] nums) {
        // 1. Сортируем, чтобы числа шли по возрастанию
        Arrays.sort(nums);

        // 2. Создаем массив для DP.
        // По условию nums[i] <= 10^6. Размер берем с запасом (+2),
        // так как мы можем обращаться к x + 1.
        int[] dp = new int[1000002];
        int maxLen = 0;

        for (int x : nums) {
            // Запоминаем текущее значение dp для x ДО его обновления
            int oldDpX = dp[x];

            // Вариант 1: оставляем x как есть.
            // Он продолжает последовательность, которая заканчивалась на x - 1.
            dp[x] = Math.max(dp[x], dp[x - 1] + 1);

            // Вариант 2: увеличиваем x на 1 (делаем x + 1).
            // Он продолжает последовательность, которая заканчивалась на x.
            // Используем oldDpX, так как dp[x] мог только что обновиться в Варианте 1
            dp[x + 1] = Math.max(dp[x + 1], oldDpX + 1);

            // Обновляем глобальный максимум
            maxLen = Math.max(maxLen, Math.max(dp[x], dp[x + 1]));
        }

        return maxLen;
    }
}
